/**
 * エージェントのシステムプロンプトを取得
 * agent-router.ts の各 run関数の先頭で呼ぶ
 */
export function getPersona(agentId: AgentId): string {
  return AGENT_PERSONA[agentId] ?? AGENT_PERSONA.shikishima;
}

/**
 * メッセージにペルソナを付加して返す
 */
export function withPersona(agentId: AgentId, message: string): string {
  const persona = getPersona(agentId);
  return `${persona}\n\n---\n\n${message}`;
}
